-- ============================================================================
-- Astro Analytics Pro - Esquema Inicial en Supabase (PostgreSQL 17)
-- ============================================================================
-- Cumple con las mejores prácticas de seguridad de Supabase:
--  * RLS habilitado en todas las tablas de `public`
--  * Acceso `anon` completamente revocado
--  * Funciones SECURITY DEFINER aisladas en esquema `private` (no expuesto)
--  * Predicados con `(select auth.uid())` para optimización de consultas
--  * Políticas separadas por operación (SELECT/INSERT/UPDATE/DELETE)
-- ============================================================================

-- Esquema privado no expuesto por PostgREST para funciones auxiliares de RLS
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC;
GRANT USAGE ON SCHEMA private TO authenticated;

-- 1. Tabla de perfiles y control de acceso (roles y revocación inmediata)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    role TEXT NOT NULL DEFAULT 'viewer' CHECK (role IN ('admin', 'viewer')),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Trigger para crear el perfil automáticamente al invitar/crear usuario
CREATE OR REPLACE FUNCTION private.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, private
AS $$
BEGIN
    INSERT INTO public.profiles (id, email, role, active)
    VALUES (NEW.id, NEW.email, 'viewer', true)
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION private.handle_new_user();

-- 2. Tabla principal de sorteos históricos (Astro Luna y Astro Sol)
CREATE TABLE IF NOT EXISTS public.sorteos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loteria TEXT NOT NULL CHECK (loteria IN ('luna', 'sol')),
    fecha DATE NOT NULL,
    numero CHAR(4) NOT NULL CHECK (numero ~ '^[0-9]{4}$'),
    signo TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_sorteos_loteria_fecha UNIQUE (loteria, fecha)
);

CREATE INDEX IF NOT EXISTS idx_sorteos_loteria_fecha
    ON public.sorteos (loteria, fecha DESC);

-- 3. Listas personalizadas por usuario (Radiografía de Apuestas)
CREATE TABLE IF NOT EXISTS public.listas_usuario (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL DEFAULT 'Principal',
    numeros TEXT[] NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_lista_usuario_nombre UNIQUE (user_id, nombre)
);

CREATE INDEX IF NOT EXISTS idx_listas_usuario_user_id
    ON public.listas_usuario (user_id);

-- ============================================================================
-- FUNCIONES AUXILIARES EN ESQUEMA PRIVADO (NO EXPUESTAS A API PÚBLICA)
-- ============================================================================

CREATE OR REPLACE FUNCTION private.is_active_user()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT auth.uid() IS NOT NULL AND EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = auth.uid()
          AND active = true
    );
$$;

CREATE OR REPLACE FUNCTION private.is_admin_user()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT auth.uid() IS NOT NULL AND EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE id = auth.uid()
          AND active = true
          AND role = 'admin'
    );
$$;

REVOKE ALL ON FUNCTION private.is_active_user() FROM PUBLIC;
REVOKE ALL ON FUNCTION private.is_admin_user() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION private.is_active_user() TO authenticated;
GRANT EXECUTE ON FUNCTION private.is_admin_user() TO authenticated;

-- ============================================================================
-- PERMISOS EXPLÍCITOS Y ROW LEVEL SECURITY (RLS)
-- ============================================================================

REVOKE ALL ON public.profiles FROM anon;
REVOKE ALL ON public.sorteos FROM anon;
REVOKE ALL ON public.listas_usuario FROM anon;

GRANT SELECT ON public.profiles TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.sorteos TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.listas_usuario TO authenticated;

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sorteos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listas_usuario ENABLE ROW LEVEL SECURITY;

-- Políticas: public.profiles
DROP POLICY IF EXISTS "profiles_select_own" ON public.profiles;
CREATE POLICY "profiles_select_own"
    ON public.profiles
    FOR SELECT
    TO authenticated
    USING ((select auth.uid()) = id);

-- Políticas: public.sorteos
DROP POLICY IF EXISTS "sorteos_select_active" ON public.sorteos;
CREATE POLICY "sorteos_select_active"
    ON public.sorteos
    FOR SELECT
    TO authenticated
    USING (private.is_active_user());

DROP POLICY IF EXISTS "sorteos_insert_admin" ON public.sorteos;
CREATE POLICY "sorteos_insert_admin"
    ON public.sorteos
    FOR INSERT
    TO authenticated
    WITH CHECK (private.is_admin_user());

DROP POLICY IF EXISTS "sorteos_update_admin" ON public.sorteos;
CREATE POLICY "sorteos_update_admin"
    ON public.sorteos
    FOR UPDATE
    TO authenticated
    USING (private.is_admin_user())
    WITH CHECK (private.is_admin_user());

-- Políticas: public.listas_usuario
DROP POLICY IF EXISTS "listas_select_own" ON public.listas_usuario;
CREATE POLICY "listas_select_own"
    ON public.listas_usuario
    FOR SELECT
    TO authenticated
    USING ((select auth.uid()) = user_id AND private.is_active_user());

DROP POLICY IF EXISTS "listas_insert_own" ON public.listas_usuario;
CREATE POLICY "listas_insert_own"
    ON public.listas_usuario
    FOR INSERT
    TO authenticated
    WITH CHECK ((select auth.uid()) = user_id AND private.is_active_user());

DROP POLICY IF EXISTS "listas_update_own" ON public.listas_usuario;
CREATE POLICY "listas_update_own"
    ON public.listas_usuario
    FOR UPDATE
    TO authenticated
    USING ((select auth.uid()) = user_id AND private.is_active_user())
    WITH CHECK ((select auth.uid()) = user_id AND private.is_active_user());

DROP POLICY IF EXISTS "listas_delete_own" ON public.listas_usuario;
CREATE POLICY "listas_delete_own"
    ON public.listas_usuario
    FOR DELETE
    TO authenticated
    USING ((select auth.uid()) = user_id AND private.is_active_user());
